-- 3. Tabel Asesmen Kesehatan Mental
CREATE TABLE asesmen_kesehatan (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nim VARCHAR(20) NOT NULL,
    tanggal_asesmen DATE NOT NULL,
    skor_c1_depresi INT NOT NULL,
    skor_c2_kecemasan INT NOT NULL,
    skor_c3_stres INT NOT NULL,
    skor_c4_penurunan_ipk DECIMAL(3, 2) NOT NULL,
    skor_c5_gangguan_tidur INT NOT NULL,
    FOREIGN KEY (nim) REFERENCES mahasiswa(nim) ON DELETE CASCADE
);

-- 4. Tabel Hasil Triase SPK
CREATE TABLE hasil_spk (
    id INT AUTO_INCREMENT PRIMARY KEY,
    asesmen_id INT NOT NULL,
    nilai_saw DECIMAL(6, 4) NOT NULL,
    ranking_urgensi INT NOT NULL,
    tingkat_urgensi VARCHAR(50) NOT NULL,
    rekomendasi_tindakan TEXT NOT NULL,
    status_rujukan ENUM('Menunggu', 'Dijadwalkan', 'Selesai') DEFAULT 'Menunggu',
    FOREIGN KEY (asesmen_id) REFERENCES asesmen_kesehatan(id) ON DELETE CASCADE
);

-- 5. Tabel Konselor Kampus
CREATE TABLE konselor (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nama_konselor VARCHAR(100) NOT NULL,
    spesialisasi VARCHAR(100) NOT NULL,
    kontak VARCHAR(20) NOT NULL,
    status_aktif BOOLEAN DEFAULT TRUE
